const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname,'../../admin/app/lib/async-controls.ts'),'utf8');
const code = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const context = {exports:{}};
vm.runInNewContext(code,context);
const gate = context.exports.createRequestGate();
const first = gate.begin();
const second = gate.begin();
assert.equal(gate.isCurrent(first),false);
assert.equal(gate.isCurrent(second),true);
gate.invalidate();
assert.equal(gate.isCurrent(second),false);
const third = gate.begin();
assert.equal(gate.isCurrent(third),true);
const lock = context.exports.createActionLock();
assert.equal(lock.acquire(),true);
assert.equal(lock.acquire(),false);
assert.equal(lock.isLocked(),true);
lock.release();
assert.equal(lock.isLocked(),false);
assert.equal(lock.acquire(),true);
console.log('Admin async controls: stale selections, closed views and synchronous duplicate-action prevention passed.');
